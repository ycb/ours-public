#!/usr/bin/env node
/**
 * Writes one self-contained file of the `notify` Edge Function, for pasting into the Supabase
 * dashboard editor (Edge Functions → notify → Code) when the CLI isn't available.
 *
 *   node scripts/bundle-notify-function.mjs > ~/Documents/notify-function.ts
 *
 * It inlines supabase/functions/_shared/*.mjs into supabase/functions/notify/index.ts. Regenerate it
 * after any change to those files; never edit the output by hand.
 */
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(resolve(root, path), "utf8");
const unexport = (source) => source.replace(/^export /gm, "");

const index = read("supabase/functions/notify/index.ts")
  .replace(/^import \{[^}]*\} from "\.\.\/_shared\/notify\.mjs";\n/m, "")
  .replace(/^import \{[^}]*\} from "\.\.\/_shared\/resend\.mjs";\n/m, "");
const [head, rest] = index.split(/\nconst env = /);
if (rest === undefined) throw new Error("index.ts layout changed: update this script");

process.stdout.write(
  [
    "// @ts-nocheck: plain-JS helpers inlined from the repo's .mjs files.",
    "// Generated by scripts/bundle-notify-function.mjs from supabase/functions — do not edit by hand.",
    head,
    "// ---- inlined from supabase/functions/_shared/notify.mjs ----",
    unexport(read("supabase/functions/_shared/notify.mjs")),
    "// ---- inlined from supabase/functions/_shared/resend.mjs ----",
    unexport(read("supabase/functions/_shared/resend.mjs")),
    "// ---- function ----",
    `const env = ${rest}`,
  ].join("\n"),
);
